import Prism from 'prismjs';

/**
 * Custom Prism language definition for immudb SQL.
 * Extends standard SQL with immudb-specific keywords, functions, and types
 * added in the feat/auditlog branch.
 */
Prism.languages.immudbsql = {
	comment: {
		pattern: /(^|[^\\])(?:\/\*[\s\S]*?\*\/|(?:--|\/\/).*)/,
		lookbehind: true,
	},
	string: {
		pattern: /(^|[^@\\])("|')(?:\\[\s\S]|(?!\2)[^\\]|\2\2)*\2/,
		greedy: true,
		lookbehind: true,
	},
	variable: /@[\w.$]+/,
	function: /\b(?:ROW_NUMBER|RANK|DENSE_RANK|LAG|LEAD|FIRST_VALUE|LAST_VALUE|NTILE|COUNT|SUM|AVG|MIN|MAX|ABS|CEIL|CEILING|FLOOR|ROUND|POWER|SQRT|MOD|SIGN|CONCAT|CONCAT_WS|REPLACE|REVERSE|LEFT|RIGHT|LPAD|RPAD|SPLIT_PART|INITCAP|REPEAT|POSITION|MD5|REGEXP_REPLACE|TRANSLATE|SUBSTR|STRPOS|LENGTH|UPPER|LOWER|TRIM|LTRIM|RTRIM|SUBSTRING|NOW|DATE_TRUNC|TO_CHAR|DATE_PART|AGE|EXTRACT|CLOCK_TIMESTAMP|COALESCE|NULLIF|GREATEST|LEAST|GEN_RANDOM_UUID|RANDOM|NEXTVAL|CURRVAL|TO_NUMBER|CURRENT_DATABASE|CURRENT_SCHEMA|CURRENT_USER|FORMAT_TYPE|PG_ENCODING_TO_CHAR|JSON_TYPEOF|IF)(?=\s*\()/i,
	type: {
		pattern: /\b(?:INTEGER|VARCHAR|BOOLEAN|BLOB|TIMESTAMP|JSON|BIGINT|INT|INT4|INT8|SMALLINT|SERIAL|DOUBLE|REAL|NUMERIC|DECIMAL|BYTEA|JSONB|TIMESTAMPTZ|TEXT|FLOAT4|FLOAT8|CHAR|CHARACTER|ANY)\b/i,
		alias: 'class-name',
	},
	keyword: /\b(?:SELECT|FROM|WHERE|AND|OR|NOT|INSERT|INTO|VALUES|UPDATE|SET|DELETE|CREATE|TABLE|INDEX|ON|DROP|ALTER|ADD|COLUMN|PRIMARY|KEY|UNIQUE|IF|EXISTS|BEGIN|TRANSACTION|COMMIT|ROLLBACK|UPSERT|USE|DATABASE|DATABASES|SHOW|TABLES|DESCRIBE|GRANT|REVOKE|AS|IS|NULL|IN|BETWEEN|LIKE|ORDER|BY|ASC|DESC|LIMIT|OFFSET|GROUP|HAVING|DISTINCT|UNION|ALL|JOIN|INNER|LEFT|RIGHT|OUTER|CASE|WHEN|THEN|ELSE|END|CAST|TRUE|FALSE|WITH|RECURSIVE|OVER|PARTITION|EXCEPT|INTERSECT|RETURNING|CONFLICT|DO|NOTHING|EXCLUDED|ILIKE|EXPLAIN|FETCH|FIRST|ROWS|ONLY|NULLS|LAST|CROSS|FULL|NATURAL|USING|DEFAULT|VIEW|SEQUENCE|NEXTVAL|CURRVAL|FOREIGN|REFERENCES|CHECK|CONSTRAINT|CASCADE|RESTRICT|TYPE|RENAME|TO|AFTER|BEFORE|SINCE|TX|UNTIL)\b/i,
	boolean: /\b(?:TRUE|FALSE)\b/i,
	number: /\b0x[\da-f]+\b|\b\d+(?:\.\d*)?|\B\.\d+\b/i,
	operator: /[-+*\/=%^~]|&&?|\|\|?|!=?|<(?:=>?|<|>)?|>[>=]?|\b(?:AND|BETWEEN|IN|LIKE|ILIKE|NOT|OR|IS|EXISTS)\b/i,
	punctuation: /[;[\]()`,.]/,
};

// Register as 'sql' alias so existing components pick it up
Prism.languages.sql = Prism.languages.immudbsql;

export default Prism;
